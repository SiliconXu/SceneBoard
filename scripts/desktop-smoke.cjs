const { _electron, expect } = require('@playwright/test')
const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')
const { unzipSync } = require('fflate')

;(async () => {
  const executablePath = process.env.SCENEBOARD_EXECUTABLE
  const application = await _electron.launch(executablePath ? { executablePath } : { args: [path.join(__dirname, '..', 'electron/main.cjs')] })
  let page
  let failed = false
  try {
    page = await application.firstWindow()
    await expect(page.getByRole('heading', { name: '先选择一种背景' })).toBeVisible()
    const locations = await application.evaluate(({ app }) => ({
      user: app.getPath('userData'), session: app.getPath('sessionData'), temp: app.getPath('temp'), logs: app.getPath('logs'), crashes: app.getPath('crashDumps'),
    }))
    const root = executablePath ? path.dirname(path.resolve(executablePath)) : path.resolve(__dirname, '..', '.portable-dev')
    for (const directory of Object.values(locations)) assert.ok(directory.startsWith(root + path.sep), `${directory} is outside the portable folder`)
    const png = await page.evaluate(() => {
      const canvas = document.createElement('canvas'); canvas.width = 800; canvas.height = 600
      const ctx = canvas.getContext('2d'); ctx.fillStyle = '#eeeeee'; ctx.fillRect(0, 0, 800, 600)
      return canvas.toDataURL().split(',')[1]
    })
    await page.getByTestId('background-input').setInputFiles({ name: 'portable-map.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
    const projectPath = path.join(root, 'projects', 'smoke.frame.json')
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, projectPath)
    await page.getByRole('button', { name: '保存项目', exact: false }).click()
    await expect(page.getByRole('status')).toContainText('项目已保存')
    const project = JSON.parse(await fs.readFile(projectPath, 'utf8'))
    assert.equal(project.background.width, 800)
    assert.ok(project.background.src.startsWith('data:image/png;base64,'))
    // Cancel must leave the current project dirty.
    await page.getByTestId('layer-input').setInputFiles({ name: 'actor.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
    await application.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }) })
    await page.getByRole('button', { name: '保存项目', exact: false }).click()
    await expect(page.locator('.unsaved-dot')).toBeVisible()
    // An export outside the app folder must fail, rather than writing to this computer.
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, path.join(root, '..', 'outside.json'))
    await page.getByRole('button', { name: '导出', exact: true }).click()
    await page.getByRole('button', { name: '导出坐标' }).click()
    await expect(page.getByRole('status')).toContainText('便携版只能保存')
    await page.getByRole('button', { name: '关闭提示' }).click()
    const pngPath = path.join(root, 'exports', 'smoke.png')
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, pngPath)
    await page.getByRole('button', { name: '导出', exact: true }).click()
    await page.getByRole('button', { name: '合成图片' }).click()
    await expect(page.getByRole('status')).toContainText('合成 PNG 已导出')
    assert.equal((await fs.readFile(pngPath)).subarray(1, 4).toString(), 'PNG')
    // Single-object export must reach the desktop save bridge for every source format.
    for (const format of ['png', 'jpeg', 'webp']) {
      const image = await page.evaluate(format => {
        const canvas = document.createElement('canvas'); canvas.width = 20; canvas.height = 10
        const ctx = canvas.getContext('2d'); ctx.fillStyle = 'rgba(0,255,0,.5)'; ctx.fillRect(0, 0, 10, 10)
        return canvas.toDataURL(`image/${format}`, 1).split(',')[1]
      }, format)
      const extension = format === 'jpeg' ? 'jpg' : format
      await page.getByTestId('layer-input').setInputFiles({ name: `sprite.${extension}`, mimeType: `image/${format}`, buffer: Buffer.from(image, 'base64') })
      const target = path.join(root, 'exports', `sprite-smoke.${extension}`)
      await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async (_window, options) => { globalThis.objectExportOptions = options; return { canceled: false, filePath: target } } }, target)
      await page.getByRole('button', { name: '导出', exact: true }).click()
      await page.getByRole('button', { name: '导出选中对象' }).click()
      await expect(page.locator('.toast')).toContainText('对象图片已导出')
      const output = await fs.readFile(target)
      const options = await application.evaluate(() => globalThis.objectExportOptions)
      assert.deepEqual(options.filters[0].extensions, [extension])
      if (format === 'png') assert.equal(output.subarray(1, 4).toString(), 'PNG')
      else if (format === 'jpeg') assert.deepEqual([...output.subarray(0, 3)], [255, 216, 255])
      else assert.equal(output.subarray(8, 12).toString(), 'WEBP')
      await page.getByRole('button', { name: '删除图片' }).first().click()
    }
    await page.getByRole('button', { name: '导出', exact: true }).click()
    await page.getByRole('button', { name: '复制坐标' }).click()
    const copied = await application.evaluate(({ clipboard }) => clipboard.readText())
    assert.equal(JSON.parse(copied).background.width, 800)
    // Clear dirty state to close without the confirmation dialog.
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, projectPath)
    await page.getByRole('button', { name: '保存项目', exact: false }).click()
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    await page.getByTestId('project-input').setInputFiles(projectPath)
    await expect(page.locator('.toast')).toContainText('项目已恢复')
    await expect(page.getByTestId('image-layer')).toHaveCount(1)
    // Project export uses its dedicated multi-file bridge; native cancellation writes nothing.
    await application.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }) })
    await page.getByRole('button', { name: '导出', exact: true }).click()
    await page.getByRole('button', { name: '导出 Pygame Zero 项目…' }).click()
    await page.getByRole('button', { name: '导出项目文件夹…' }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await expect(page.getByRole('button', { name: '导出项目文件夹…' })).toBeEnabled()
    const pygamePath = path.join(root, 'exports', `pygame-smoke-${Date.now()}`)
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, pygamePath)
    await page.getByRole('button', { name: '导出项目文件夹…' }).click()
    await expect(page.locator('.toast')).toContainText('Pygame Zero 项目已导出')
    assert.ok((await fs.readFile(path.join(pygamePath, 'main.py'), 'utf8')).includes("actor = Actor('actor')"))
    assert.equal((await fs.readFile(path.join(pygamePath, 'images/background.png'))).subarray(1, 4).toString(), 'PNG')
    assert.equal((await fs.readFile(path.join(pygamePath, 'images/actor.png'))).subarray(1, 4).toString(), 'PNG')
    await page.getByRole('button', { name: '导出', exact: true }).click()
    await page.getByRole('button', { name: '导出 Pygame Zero 项目…' }).click()
    await page.getByRole('button', { name: '导出项目文件夹…' }).click()
    await expect(page.getByRole('dialog').getByRole('alert')).toContainText('已存在')
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, path.join(root, '..', 'outside-project'))
    await page.getByRole('button', { name: '导出项目文件夹…' }).click()
    await expect(page.getByRole('dialog').getByRole('alert')).toContainText('便携版只能保存')
    await page.getByRole('dialog').getByRole('button', { name: '取消' }).click()
    // Color background export must have an empty images directory and no background image.
    await page.getByRole('button', { name: '替换背景', exact: false }).click()
    await page.getByRole('button', { name: '创建纯色背景', exact: true }).click()
    await page.getByRole('button', { name: '创建画布' }).click()
    await page.getByRole('button', { name: '替换并清空' }).click()
    const colorPath = path.join(root, 'exports', `pygame-color-smoke-${Date.now()}`)
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, colorPath)
    await page.getByRole('button', { name: '导出', exact: true }).click()
    await page.getByRole('button', { name: '导出 Pygame Zero 项目…' }).click()
    await page.getByRole('button', { name: '导出项目文件夹…' }).click()
    await expect(page.locator('.toast')).toContainText('Pygame Zero 项目已导出')
    assert.deepEqual(await fs.readdir(path.join(colorPath, 'images')), [])
    assert.ok((await fs.readFile(path.join(colorPath, 'main.py'), 'utf8')).includes("screen.fill('#000000')"))
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, projectPath)
    await page.getByRole('button', { name: '保存项目', exact: false }).click()
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    // Current image edits and independent animation must also use the native save bridges.
    const editSource = await page.evaluate(() => {
      const canvas = document.createElement('canvas'); canvas.width = 20; canvas.height = 12
      const ctx = canvas.getContext('2d')
      ctx.fillStyle = '#ff0000'; ctx.fillRect(2, 1, 4, 4)
      ctx.fillStyle = '#0000ff'; ctx.fillRect(6, 1, 6, 4)
      ctx.fillStyle = 'rgba(0,255,0,.5)'; ctx.fillRect(2, 5, 10, 3)
      ctx.fillStyle = `rgba(0,0,0,${1 / 255})`; ctx.fillRect(0, 0, 1, 1)
      return canvas.toDataURL()
    })
    await page.getByTestId('project-input').setInputFiles({ name: 'edits.frame.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({
      version: 4, background: { kind: 'color', name: '背景', color: '#203040', width: 320, height: 240 },
      layers: [{ id: 'hero', name: 'hero', src: editSource, x: 20.25, y: 30.5, width: 40, height: 24 }],
    })) })
    await expect(page.locator('.toast')).toContainText('项目已恢复')
    await page.locator('[data-card-id="hero"]').click()
    await page.getByRole('button', { name: '水平翻转', exact: true }).click()
    await page.getByRole('button', { name: '垂直翻转', exact: true }).click()
    await page.getByRole('button', { name: '裁剪透明留白…' }).click()
    await expect(page.getByRole('slider')).toHaveValue('3')
    await page.getByRole('button', { name: '确认裁剪' }).click()
    const editedPath = path.join(root, 'exports', 'edited-smoke.png')
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, editedPath)
    await page.getByRole('button', { name: '导出', exact: true }).click()
    await page.getByRole('button', { name: '导出选中对象' }).click()
    await expect(page.locator('.toast')).toContainText('对象图片已导出')
    const edited = await fs.readFile(editedPath)
    assert.deepEqual([edited.readUInt32BE(16), edited.readUInt32BE(20)], [20, 14])
    await page.getByRole('button', { name: '动画素材…' }).click()
    const animation = page.getByRole('dialog', { name: '动画素材', exact: true })
    await animation.getByRole('button', { name: '新增组' }).click()
    await animation.getByLabel('动画名称前缀').fill('walk')
    await animation.getByLabel('动画 FPS').fill('12')
    await animation.getByTestId('animation-input').setInputFiles([
      { name: 'first.png', mimeType: 'image/png', buffer: Buffer.from(editSource.split(',')[1], 'base64') },
      { name: 'second.png', mimeType: 'image/png', buffer: Buffer.from(editSource.split(',')[1], 'base64') },
    ])
    await expect(animation.locator('.animation-frames li')).toHaveCount(2)
    await application.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }) })
    await animation.getByRole('button', { name: '导出本组帧 ZIP' }).click()
    await expect(animation.getByRole('button', { name: '导出本组帧 ZIP' })).toBeEnabled()
    const framesPath = path.join(root, 'exports', 'walk-frames-smoke.zip')
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async (_window, options) => { globalThis.frameZipOptions = options; return { canceled: false, filePath: target } } }, framesPath)
    await animation.getByRole('button', { name: '导出本组帧 ZIP' }).click()
    await expect(animation.getByRole('button', { name: '导出本组帧 ZIP' })).toBeEnabled()
    assert.deepEqual((await application.evaluate(() => globalThis.frameZipOptions)).filters[0].extensions, ['zip'])
    const frameFiles = unzipSync(await fs.readFile(framesPath))
    assert.deepEqual(Object.keys(frameFiles), ['walk/images/', 'walk/images/walk_001.png', 'walk/images/walk_002.png'])
    await animation.getByRole('button', { name: '应用到项目' }).click()
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, projectPath)
    await page.getByRole('button', { name: '保存项目', exact: false }).click()
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    const updated = JSON.parse(await fs.readFile(projectPath, 'utf8'))
    assert.equal(updated.version, 4)
    assert.deepEqual(updated.layers[0].crop, { x: 2, y: 1, width: 10, height: 7 })
    assert.equal(updated.layers[0].flipX, true); assert.equal(updated.layers[0].flipY, true)
    assert.equal(updated.layers[0].x, 36.25); assert.equal(updated.layers[0].y, 38.5)
    assert.equal(updated.animations[0].fps, 12); assert.equal(updated.animations[0].frames.length, 2)
    await page.getByTestId('project-input').setInputFiles(projectPath)
    await expect(page.locator('.toast')).toContainText('项目已恢复')
    const animationPath = path.join(root, 'exports', `pygame-animation-smoke-${Date.now()}`)
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, animationPath)
    await page.getByRole('button', { name: '导出', exact: true }).click()
    await page.getByRole('button', { name: '导出 Pygame Zero 项目…' }).click()
    const preview = await page.getByLabel('Python 代码预览').innerText()
    await page.getByRole('button', { name: '导出项目文件夹…' }).click()
    await expect(page.locator('.toast')).toContainText('Pygame Zero 项目已导出')
    assert.equal((await fs.readFile(path.join(animationPath, 'main.py'), 'utf8')).trimEnd(), preview.trimEnd())
    assert.ok(preview.includes("'walk': 12")); assert.ok(preview.includes("#     'walk': YOUR_ACTOR,"))
    assert.deepEqual(await fs.readFile(path.join(animationPath, 'images/hero.png')), edited)
    for (const name of ['walk_001.png', 'walk_002.png']) assert.deepEqual(await fs.readFile(path.join(animationPath, 'images', name)), Buffer.from(frameFiles[`walk/images/${name}`]))
    // Verify scene history and native save checkpoints in the actual desktop renderer.
    const undo = page.getByRole('button', { name: '撤销', exact: true })
    const redo = page.getByRole('button', { name: '重做', exact: true })
    await expect(undo).toBeDisabled(); await expect(redo).toBeDisabled()
    await page.locator('[data-card-id="hero"]').click()
    for (let index = 0; index < 3; index++) await page.keyboard.down('ArrowRight')
    await page.keyboard.up('ArrowRight')
    await expect(undo).toHaveAttribute('title', /微调位置/)
    const historyPath = path.join(root, 'projects', 'history-smoke.frame.json')
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, historyPath)
    await page.getByRole('button', { name: '保存项目', exact: false }).click()
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    const moved = JSON.parse(await fs.readFile(historyPath, 'utf8'))
    assert.equal(moved.layers[0].x, 39.25)
    assert.equal(moved.history, undefined)
    await page.keyboard.press('Control+z')
    await expect(undo).toBeDisabled(); await expect(page.locator('.unsaved-dot')).toHaveCount(1)
    await page.keyboard.press('Control+y')
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    await page.keyboard.press('Control+z')
    await application.evaluate(({ dialog }) => { dialog.showSaveDialog = async () => ({ canceled: true }) })
    await page.getByRole('button', { name: '保存项目', exact: false }).click()
    await expect(page.getByRole('button', { name: '保存项目', exact: false })).toBeEnabled()
    await expect(page.locator('.unsaved-dot')).toHaveCount(1)
    await page.keyboard.press('Control+Shift+z')
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    await undo.click(); await redo.click()
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    await page.keyboard.press('Control+x')
    await expect(page.getByTestId('image-layer')).toHaveCount(0)
    await page.keyboard.press('Control+z')
    await expect(page.getByTestId('image-layer')).toHaveCount(1)
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    await application.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, historyPath)
    await page.getByRole('button', { name: '保存项目', exact: false }).click()
    await expect(page.getByRole('button', { name: '保存项目', exact: false })).toBeEnabled()
    assert.deepEqual(JSON.parse(await fs.readFile(historyPath, 'utf8')), moved)
    await page.getByTestId('project-input').setInputFiles(historyPath)
    await expect(page.locator('.toast')).toContainText('项目已恢复')
    await expect(undo).toBeDisabled(); await expect(redo).toBeDisabled()
    await page.screenshot({ path: path.join(__dirname, '..', 'test-results', 'desktop-smoke-success.png') })
    console.log('Desktop smoke passed: undo/redo shortcuts, grouped arrows, cut restoration, native save/cancellation checkpoints and history reset; portable paths; project/PNG/JPEG/WebP saves; flip/trim and v4 reopen; animation ZIP/cancellation; Pygame image/color/animation exports and code preview; clipboard, overwrite and path restrictions.')
  } catch (error) {
    failed = true
    if (page) {
      await page.screenshot({ path: path.join(__dirname, '..', 'test-results', 'desktop-smoke-failure.png') }).catch(() => {})
      console.error((await page.locator('body').innerText()).slice(-4500))
    }
    throw error
  } finally {
    if (failed) application.process().kill()
    await application.close().catch(error => { if (!failed) throw error })
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
