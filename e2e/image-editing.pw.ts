test('tight trim changes a landscape image into a portrait with no fully transparent outer edge', async ({ page }) => {
  await page.goto('/')
  await openScene(page, await source(page, 'portrait'), { width: 100, height: 60 })
  await page.getByRole('button', { name: '裁剪透明留白…' }).click()
  const dialog = page.getByRole('dialog', { name: '裁剪透明留白', exact: true })
  await expect(dialog.getByRole('button', { name: '确认裁剪' })).toBeEnabled()
  await expect(dialog).toContainText('不保持原图长宽比')
  const beforeBox = (await dialog.locator('.crop-preview-area').first().boundingBox())!
  const afterBox = (await dialog.locator('.crop-preview-area.is-cropped').boundingBox())!
  expect(beforeBox.width / beforeBox.height).toBeCloseTo(100 / 60, 2)
  expect(afterBox.width / afterBox.height).toBeCloseTo(3 / 10, 2)
  await page.screenshot({ path: 'test-results/crop-tight-portrait-preview.png', fullPage: true })
  await dialog.getByRole('button', { name: '确认裁剪' }).click()
  const saved = await save(page)
  expect(saved.layers[0]).toMatchObject({ x: 60.25, y: 35.5, width: 15, height: 50, crop: { x: 8, y: 1, width: 3, height: 10 } })
  const image = await pixels(page, await objectBytes(page))
  expect([image.width, image.height]).toEqual([15, 50])
  const alpha = (x: number, y: number) => image.data[(y * image.width + x) * 4 + 3]
  expect(Array.from({ length: image.width }, (_, x) => alpha(x, 0)).some(value => value! > 0)).toBe(true)
  expect(Array.from({ length: image.width }, (_, x) => alpha(x, image.height - 1)).some(value => value! > 0)).toBe(true)
  expect(Array.from({ length: image.height }, (_, y) => alpha(0, y)).some(value => value! > 0)).toBe(true)
  expect(Array.from({ length: image.height }, (_, y) => alpha(image.width - 1, y)).some(value => value! > 0)).toBe(true)
  const zip = unzipSync(await projectZip(page))
  expect(await pixels(page, zip['pygame_project/images/hero.png']!)).toEqual(image)
  await page.getByTestId('project-input').setInputFiles({ name: 'portrait.frame.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(saved)) })
  await page.locator('[data-card-id="hero"]').click()
  expect(await pixels(page, await objectBytes(page))).toEqual(image)
  await page.getByRole('button', { name: '裁剪透明留白…' }).click()
  await expect(dialog).toContainText('没有可裁剪的透明留白')
  await expect(dialog.getByRole('button', { name: '确认裁剪' })).toBeDisabled()
})

