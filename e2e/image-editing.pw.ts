import { test, expect } from '@playwright/test'
import { writeFile } from 'node:fs/promises'
import { unzipSync, strFromU8 } from 'fflate'
import { source, openScene, bytes, save, pixels, objectBytes, projectZip } from './round3-utils'

test('flip content only, save/reopen, mixed selection, clipboard and all export paths', async ({ page }) => {
  await page.goto('/'); const src = await source(page); await openScene(page, src)
  const before = await pixels(page, await objectBytes(page))
  await page.getByRole('button', { name: '水平翻转', exact: true }).click()
  await page.getByRole('button', { name: '垂直翻转', exact: true }).click()
  const after = await pixels(page, await objectBytes(page))
  const at = (data: typeof before, x: number, y: number) => data.data.slice((y * data.width + x) * 4, (y * data.width + x) * 4 + 4)
  expect(at(before, 6, 4)).toEqual([255, 0, 0, 255])
  expect(at(after, 33, 19)).toEqual(at(before, 6, 4))
  let saved = await save(page)
  expect(saved.version).toBe(4)
  expect(saved.layers[0]).toMatchObject({ src, flipX: true, flipY: true, x: 20.25, y: 30.5, width: 40, height: 24 })
  await page.getByTestId('project-input').setInputFiles({ name: 'again.frame.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(saved)) })
  await page.locator('[data-card-id="hero"]').click()
  expect(await pixels(page, await objectBytes(page))).toEqual(after)
  const zip = unzipSync(await projectZip(page))
  expect(await pixels(page, zip['pygame_project/images/hero.png']!)).toEqual(after)
  expect(strFromU8(zip['pygame_project/main.py']!)).toContain('hero.pos = (40, 43)')
  await page.getByRole('button', { name: '导出', exact: true }).click()
  const composition = await pixels(page, await bytes(page, () => page.getByRole('button', { name: '合成图片' }).click()))
  expect(at(composition, 53, 50)).toEqual([255, 0, 0, 255])
  await page.locator('[data-card-id="shape"]').click({ modifiers: ['Control'] })
  await page.getByRole('button', { name: '水平翻转', exact: true }).click()
  saved = await save(page)
  expect(saved.layers[0].flipX).toBe(false); expect(saved.layers[1].flipX).toBeUndefined()
  await page.keyboard.press('Control+c'); await page.keyboard.press('Control+v')
  saved = await save(page)
  expect(saved.layers).toHaveLength(4); expect(saved.layers[2]).toMatchObject({ flipX: false, flipY: true })
  await page.locator('[data-card-id="hero"]').click()
  await page.getByRole('button', { name: '垂直翻转', exact: true }).click()
  expect(await pixels(page, await objectBytes(page))).toEqual(before)
  await page.screenshot({ path: 'test-results/round3-flip.png', fullPage: true })
})

for (const flipX of [false, true]) for (const flipY of [false, true]) {
  test(`crop preview keeps visible pixels in place, flip ${flipX}/${flipY}, reopen and export`, async ({ page }) => {
    await page.goto('/'); const src = await source(page); await openScene(page, src, { flipX, flipY })
    await save(page)
    await page.getByRole('button', { name: '裁剪透明留白…' }).click()
    const dialog = page.getByRole('dialog', { name: '裁剪透明留白', exact: true })
    await expect(dialog.getByRole('button', { name: '确认裁剪' })).toBeEnabled()
    await dialog.getByText('九点锚点变化').click()
    await expect(dialog.getByText('midbottom', { exact: true })).toBeVisible()
    await page.keyboard.press('Delete')
    await dialog.getByRole('button', { name: '取消' }).click()
    await expect(page.getByTestId('layer-card')).toHaveCount(2)
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
    await page.getByRole('button', { name: '裁剪透明留白…' }).click()
    await dialog.getByRole('button', { name: '确认裁剪' }).click()
    await expect(page.locator('.unsaved-dot')).toHaveCount(1)
    const saved = await save(page)
    expect(saved.layers[0]).toMatchObject({ src, x: 20.25 + (flipX ? 16 : 4), y: 30.5 + (flipY ? 8 : 2), width: 20, height: 14, crop: { x: 2, y: 1, width: 10, height: 7 } })
    const single = await pixels(page, await objectBytes(page))
    expect([single.width, single.height]).toEqual([20, 14])
    expect(single.data.some((alpha, i) => i % 4 === 3 && alpha === 128)).toBe(true)
    expect(single.data.every((alpha, i) => i % 4 !== 3 || alpha > 0)).toBe(true)
    const edgeX = flipX ? 19 : 0, edgeY = flipY ? 0 : 13
    const offset = (edgeY * single.width + edgeX) * 4
    expect(single.data.slice(offset, offset + 4)).toEqual([0, 255, 0, 128])
    const zipBytes = await projectZip(page), zip = unzipSync(zipBytes)
    expect(await pixels(page, zip['pygame_project/images/hero.png']!)).toEqual(single)
    if (flipX && flipY) await writeFile('test-results/pygame-runtime-edits.zip', zipBytes)
    await page.getByTestId('project-input').setInputFiles({ name: 'cropped.frame.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(saved)) })
    await page.locator('[data-card-id="hero"]').click()
    expect(await pixels(page, await objectBytes(page))).toEqual(single)
    await page.getByRole('button', { name: '裁剪透明留白…' }).click()
    await expect(dialog).toContainText('没有可裁剪的透明留白')
    await expect(dialog.getByRole('button', { name: '确认裁剪' })).toBeDisabled()
    await page.screenshot({ path: `test-results/round3-crop-${flipX}-${flipY}.png`, fullPage: true })
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
  })
}

test('transparent and opaque sources cannot crop, malformed crop loading preserves current scene', async ({ page }) => {
  await page.goto('/')
  for (const mode of ['empty', 'opaque']) {
    await openScene(page, await source(page, mode)); await save(page)
    await page.getByRole('button', { name: '裁剪透明留白…' }).click()
    await expect(page.getByRole('dialog')).toContainText(mode === 'empty' ? '完全透明' : '没有可裁剪')
    await expect(page.getByRole('button', { name: '确认裁剪' })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(page.locator('.unsaved-dot')).toHaveCount(0)
  }
  const saved = await save(page)
  saved.layers[0].crop = { x: 19, y: 0, width: 10, height: 6 }
  await page.getByTestId('project-input').setInputFiles({ name: 'bad.frame.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(saved)) })
  await expect(page.locator('.toast')).toContainText('裁剪区域超出了')
  expect((await save(page)).layers[0].crop).toBeUndefined()
})

